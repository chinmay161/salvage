"""tools/build_docs.py: FORMAT-SPEC.md, FIELD-LOG.md and the README formats table.

Runs on a copy of tests/fixtures/build_docs/ (a miniature repo with spec
and log files), with a hand-made decoder list instead of real discovery.
"""

import importlib.util
import io
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / "tests" / "fixtures" / "build_docs"


def _load(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module      # dataclasses look their module up here
    spec.loader.exec_module(module)
    return module


bd = _load("build_docs", ROOT / "tools" / "build_docs.py")
FI = bd.FormatInfo
FORMATS = {
    "libra98": FI("libra98", "LIBRA-98", (".lb9",), True),
    "lablog": FI("lablog", "LABLOG", (), False),
    "vault": FI("vault", "VAULT", (".vlt",), False),
    "wks": FI("wks", "WKS", (".wks", ".wk1"), False),
    "stub": FI("stub", "STUB", (".stub",), False),
}


class Base(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name) / "repo"
        shutil.copytree(FIXTURE, self.root)

    def tearDown(self):
        self._tmp.cleanup()

    def generate(self, formats=FORMATS):
        return bd.generate(self.root, formats)

    def run_docs(self, formats=FORMATS, **kw):
        out = io.StringIO()
        code = bd.run(self.root, formats, out=out, **kw)
        return code, out.getvalue()

    def write(self, rel: str, text: str) -> None:
        (self.root / rel).write_bytes(text.encode("utf-8"))


class MarkdownHelperTests(unittest.TestCase):
    def test_demote_skips_code_fences_and_caps_at_6(self):
        text = "# A\n## B\nnot # a heading\n```\n# code\n```\n###### deep\n#nospace\n"
        self.assertEqual(bd.demote(text),
                         "## A\n### B\nnot # a heading\n```\n# code\n```\n###### deep\n#nospace\n")

    def test_slugs_match_github_and_deduplicate(self):
        text = "## Output format — PROVISIONAL\n## Summary\n### Summary\n## `x` = y!\n"
        self.assertEqual([a for *_, a in bd.anchors(text)],
                         ["output-format--provisional", "summary", "summary-1", "x--y"])

    def test_rebase_links(self):
        text = ("[a](../../salvage/x.py) [b](#anchor) [c](https://e.org/x) "
                "[d](other.md)\n```\n[e](../x)\n```\n")
        self.assertEqual(bd.rebase_links(text, "docs/spec"),
                         "[a](salvage/x.py) [b](#anchor) [c](https://e.org/x) "
                         "[d](docs/spec/other.md)\n```\n[e](../x)\n```\n")


class FormatSpecTests(Base):
    def test_sections_in_format_order_stub_and_templates_excluded(self):
        files, _ = self.generate()
        spec = files["FORMAT-SPEC.md"]
        self.assertTrue(spec.startswith("<!-- Generated by tools/build_docs.py from docs/spec/. "
                                        "Do not edit by hand. -->\n\n"
                                        "# Salvage format specifications\n\n"
                                        "## How Salvage reads a file\n"))
        h2 = [title for _, level, title in bd.headings(spec) if level == 2]
        self.assertEqual(h2, ["How Salvage reads a file", "Contents", "LIBRA-98", "LABLOG",
                              "Lotus WKS", "ZETA", "Output format"])
        self.assertNotIn("STUB", spec)
        self.assertNotIn("Template.", spec)

    def test_headings_demoted_one_level(self):
        spec = self.generate()[0]["FORMAT-SPEC.md"]
        self.assertIn("\n## LIBRA-98\n\n### Summary\n", spec)
        self.assertIn("\n### Per-file output\n", spec)                 # from output-format.md
        self.assertIn("```text\n# not a heading: inside a code fence\n```", spec)

    def test_table_of_contents_links_every_section(self):
        spec = self.generate()[0]["FORMAT-SPEC.md"]
        self.assertIn("## Contents\n\n- [LIBRA-98](#libra-98)\n- [LABLOG](#lablog)\n"
                      "- [Lotus WKS](#lotus-wks)\n- [ZETA](#zeta)\n"
                      "- [Output format](#output-format)\n", spec)

    def test_links_rebased_to_repo_root(self):
        spec = self.generate()[0]["FORMAT-SPEC.md"]
        self.assertIn("[the decoder](salvagekit/formats/libra98.py)", spec)
        self.assertIn("[the output format](docs/output-format.md)", spec)

    def test_missing_sections_and_wrong_heading_warn(self):
        _, probs = self.generate()
        self.assertEqual(probs.errors, [])
        w = probs.warnings
        self.assertIn("docs/spec/wks.md: first heading must be '# WKS' (the decoder name), "
                      "found '# Lotus WKS'", w)
        for section in ("Identification", "Records", "Checksums",
                        "Compression and obfuscation", "Damage handling", "Open questions"):
            self.assertIn(f"docs/spec/wks.md: missing section '## {section}'", w)
        self.assertNotIn("docs/spec/wks.md: missing section '## Layout'", w)
        self.assertFalse([x for x in w if x.startswith(("docs/spec/libra98.md",
                                                        "docs/spec/lablog.md"))])
        self.assertIn("docs/spec/zeta.md: no decoder found for this module "
                      "(salvagekit/formats/zeta.py)", w)
        self.assertIn("VAULT: no spec (docs/spec/vault.md)", w)
        self.assertIn("VAULT: no research log (docs/log/vault.md)", w)
        self.assertFalse([x for x in w if "stub" in x.lower() or "_TEMPLATE" in x])


class FieldLogTests(Base):
    def entry_heads(self, log: str) -> list[str]:
        return [line for line in log.splitlines() if line.startswith("### ")]

    def test_entries_sorted_by_time_then_format_order_then_file_order(self):
        log = self.generate()[0]["FIELD-LOG.md"]
        self.assertEqual(self.entry_heads(log), [
            "### 2026-10-15 09:00 — [LIBRA-98] Magic is LB98",
            "### 2026-10-16 14:05 — [LIBRA-98] Record length is u16be?",
            "### 2026-10-16 14:05 — [LIBRA-98] Second entry at the same minute",
            "### 2026-10-16 14:05 — [LABLOG] Same minute as LIBRA-98",
            "### 2026-10-17 08:30 — [LABLOG] No result line here",
            "### 2026-10-17 09:00 — [LABLOG] Lowercase result",
        ])
        self.assertNotIn("stub entry", log)
        self.assertNotIn("template entry", log)

    def test_body_copied_unchanged(self):
        log = self.generate()[0]["FIELD-LOG.md"]
        self.assertIn("### 2026-10-16 14:05 — [LIBRA-98] Record length is u16be?\n\n"
                      "**Hypothesis:** bytes 2-3 are the length.\n\n"
                      "**Tried:** jumped that far.\n\n**Evidence:** 41/41 hits.\n\n"
                      "**Result:** CONFIRMED. Excludes the header.\n\n### ", log)
        self.assertTrue(log.startswith("<!-- Generated by tools/build_docs.py from docs/log/. "
                                       "Do not edit by hand. -->\n\n# Salvage field log\n"))
        self.assertIn("IST", log.split("## Summary")[0])

    def test_result_counts_and_total(self):
        log = self.generate()[0]["FIELD-LOG.md"]
        self.assertIn("| LIBRA-98 | 3 | 1 | 1 | 1 |\n"
                      "| LABLOG | 3 | 1 | 0 | 0 |\n"
                      "| **Total** | **6** | **2** | **1** | **1** |\n", log)

    def test_missing_or_bad_result_warns(self):
        _, probs = self.generate()
        self.assertIn("docs/log/lablog.md:9: entry 'No result line here' has no **Result:** "
                      "line", probs.warnings)
        self.assertIn("docs/log/lablog.md:15: Result of 'Lowercase result' must start with "
                      "CONFIRMED, REJECTED or INCONCLUSIVE, found 'confirmed'", probs.warnings)

    def test_bad_date_is_an_error_with_file_and_line(self):
        path = self.root / "docs" / "log" / "libra98.md"
        text = path.read_text(encoding="utf-8")
        self.write("docs/log/libra98.md",
                   text + "\n### 2026-02-30 10:00 — No such day\n\n**Result:** REJECTED\n"
                          "\n### yesterday — No date at all\n")
        line = len(text.splitlines()) + 2
        _, probs = self.generate()
        self.assertEqual(len(probs.errors), 2)
        self.assertTrue(probs.errors[0].startswith(f"docs/log/libra98.md:{line}: entry heading "
                                                   "must be '### YYYY-MM-DD HH:MM — <title>'"))
        self.assertTrue(probs.errors[1].startswith(f"docs/log/libra98.md:{line + 4}: "))
        # An error fails the run (even without --strict) and writes nothing.
        code, out = self.run_docs()
        self.assertEqual(code, 1)
        self.assertIn("nothing written", out)
        self.assertFalse((self.root / "FIELD-LOG.md").exists())


class ReadmeTableTests(Base):
    def test_table_rows(self):
        readme = self.generate()[0]["README.md"]
        self.assertIn(
            "<!-- formats:start -->\n"
            "| Format | Extensions | Round-trip proof | Golden cases | Spec | Log |\n"
            "|--------|------------|------------------|-------------:|------|-----|\n"
            "| LIBRA-98 | `.lb9` | yes | 2 | [yes](FORMAT-SPEC.md#libra-98) | yes |\n"
            "| LABLOG | — | no | 0 | [yes](FORMAT-SPEC.md#lablog) | yes |\n"
            "| VAULT | `.vlt` | no | 0 | no | no |\n"
            "| WKS | `.wks`, `.wk1` | no | 0 | [yes](FORMAT-SPEC.md#lotus-wks) | no |\n"
            "<!-- formats:end -->", readme)
        self.assertNotIn("STUB", readme)

    def test_no_decoders_message(self):
        readme = self.generate({"stub": FORMATS["stub"]})[0]["README.md"]
        self.assertIn("<!-- formats:start -->\nNo format decoders merged yet.\n"
                      "<!-- formats:end -->", readme)

    def test_markers_replaced_idempotently_and_nothing_else_touched(self):
        before = (self.root / "README.md").read_text(encoding="utf-8")
        self.assertEqual(self.run_docs()[0], 0)
        first = (self.root / "README.md").read_bytes()
        code, out = self.run_docs()
        self.assertEqual((code, (self.root / "README.md").read_bytes()), (0, first))
        self.assertIn("docs: nothing changed", out)
        after = first.decode("utf-8")
        head, tail = before.split("<!-- formats:start -->")[0], before.split(
            "<!-- formats:end -->")[1]
        self.assertTrue(after.startswith(head + "<!-- formats:start -->\n| Format"))
        self.assertTrue(after.endswith("<!-- formats:end -->" + tail))
        self.assertNotIn("stale content", after)

    def test_missing_markers_is_an_error(self):
        self.write("README.md", "# README without markers\n")
        _, probs = self.generate()
        self.assertEqual(probs.errors, ["README.md: needs exactly one '<!-- formats:start -->' "
                                        "followed by one '<!-- formats:end -->'"])


class RunTests(Base):
    def test_output_byte_identical_across_runs_and_copies(self):
        self.assertEqual(self.run_docs()[0], 0)
        first = {n: (self.root / n).read_bytes() for n in ("FORMAT-SPEC.md", "FIELD-LOG.md",
                                                           "README.md")}
        other = Path(self._tmp.name) / "copy"
        shutil.copytree(FIXTURE, other)
        bd.run(other, FORMATS, out=io.StringIO())
        for name, data in first.items():
            self.assertEqual((other / name).read_bytes(), data, name)
            self.assertNotIn(b"\r", data)
            self.assertTrue(data.endswith(b"\n") and not data.endswith(b"\n\n"))

    def test_check_detects_stale_files_and_writes_nothing(self):
        code, out = self.run_docs(check=True)
        self.assertEqual(code, 1)
        self.assertIn("stale: FORMAT-SPEC.md (missing)", out)
        self.assertFalse((self.root / "FORMAT-SPEC.md").exists())
        self.assertEqual(self.run_docs()[0], 0)
        code, out = self.run_docs(check=True)
        self.assertEqual(code, 0)
        self.assertIn("docs: up to date", out)
        # Hand-edit a generated file: --check names it and shows a diff.
        log = self.root / "FIELD-LOG.md"
        log.write_bytes(log.read_bytes().replace(b"| **Total** | **6**", b"| **Total** | **7**"))
        code, out = self.run_docs(check=True)
        self.assertEqual(code, 1)
        self.assertIn("stale: FIELD-LOG.md\n", out)
        self.assertIn("-| **Total** | **7**", out)
        self.assertIn("+| **Total** | **6**", out)
        self.assertNotIn("stale: FORMAT-SPEC.md", out)
        self.assertIn(b"**7**", log.read_bytes())   # --check never writes

    def test_warnings_fail_only_with_strict(self):
        code, out = self.run_docs()
        self.assertEqual(code, 0)
        self.assertIn("warning: docs/spec/wks.md: missing section", out)
        code, out = self.run_docs(strict=True)
        self.assertEqual(code, 1)
        self.assertIn("docs --strict:", out)


class RealRepoTests(unittest.TestCase):
    def test_templates_have_every_section_and_are_never_assembled(self):
        spec = (ROOT / "docs" / "spec" / "_TEMPLATE.md").read_text(encoding="utf-8")
        h2 = [t for _, level, t in bd.headings(spec) if level == 2]
        self.assertEqual(h2, list(bd.SPEC_SECTIONS))
        self.assertNotIn("_TEMPLATE", bd.doc_modules(ROOT / "docs" / "spec"))
        self.assertNotIn("_TEMPLATE", bd.doc_modules(ROOT / "docs" / "log"))
        log = (ROOT / "docs" / "log" / "_TEMPLATE.md").read_text(encoding="utf-8")
        self.assertIn("IST", log)
        probs = bd.Problems()
        entries = bd.parse_log("docs/log/_TEMPLATE.md", log, "x", probs)
        self.assertEqual((len(entries), entries[0].result, probs.errors, probs.warnings),
                         (1, "CONFIRMED", [], []))

    def test_stub_docs_follow_the_templates(self):
        probs = bd.Problems()
        text = (ROOT / "docs" / "spec" / "stub.md").read_text(encoding="utf-8")
        bd.check_spec("docs/spec/stub.md", text, bd.FormatInfo("stub", "STUB"), probs)
        log = (ROOT / "docs" / "log" / "stub.md").read_text(encoding="utf-8")
        self.assertTrue(bd.parse_log("docs/log/stub.md", log, "stub", probs))
        self.assertEqual((probs.errors, probs.warnings), ([], []))


